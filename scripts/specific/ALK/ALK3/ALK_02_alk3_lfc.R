# REPORT --------------------------------------------------------------------
summarize_drug <- function(drug) {
  df <- lfc_table %>% filter(Drug == drug)
  n_up   <- sum(df$Classification == "Upregulated")
  n_down <- sum(df$Classification == "Downregulated")
  n_other <- sum(df$Classification == "Other")
  ratio  <- if (n_down > 0) round(n_up / n_down, 2) else "Inf"
  top10_up <- df %>% filter(Classification == "Upregulated") %>%
    arrange(desc(LFC_Res_vs_Trt)) %>% slice_head(n = 10) %>% dplyr::select(Gene, LFC_Res_vs_Trt)
  top10_down <- df %>% filter(Classification == "Downregulated") %>%
    arrange(LFC_Res_vs_Trt) %>% slice_head(n = 10) %>% dplyr::select(Gene, LFC_Res_vs_Trt)
  paste0(
    "### ", drug, "\n",
    "| Class | N | % |\n|-------|---|---|\n",
    "| Upregulated | ", n_up, " | ", round(100*n_up/nrow(df),1), "% |\n",
    "| Downregulated | ", n_down, " | ", round(100*n_down/nrow(df),1), "% |\n",
    "| Other | ", n_other, " | ", round(100*n_other/nrow(df),1), "% |\n\n",
    "**Ratio Upregulated/Downregulated:** ", ratio, "\n\n",
    "**Top 10 Upregulated**\n",
    paste(capture.output(print(as.data.frame(top10_up), row.names = FALSE)), collapse = "\n"), "\n\n",
    "**Top 10 Downregulated**\n",
    paste(capture.output(print(as.data.frame(top10_down), row.names = FALSE)), collapse = "\n"), "\n\n"
  )
}

