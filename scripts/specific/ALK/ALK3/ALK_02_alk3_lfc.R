plot_heatmap_genes <- function(genes, filename, title, width = 12, height = 9) {
  genes <- union(FORCED_GENES, genes)
  genes <- genes[genes %in% rownames(mat)]
  if (length(genes) < 2) {
    cat("  ⚠", filename, "— fewer than 2 genes available, skipped\n\n")
    return(invisible(NULL))
  }
  z_mat <- t(apply(mat[genes, , drop = FALSE], 1, cal_zscore))
  ph <- pheatmap(z_mat,
           color             = heatmap_expr,
           show_rownames     = (length(genes) <= 60),
           show_colnames     = TRUE,
           fontsize_row      = 8,
           annotation_col    = annotation,
           annotation_colors = ann_colors,
           cluster_rows      = TRUE,
           cluster_cols      = TRUE,
           clustering_method = "ward.D2",
           main = paste0(title, " — ", OUT_PREFIX, " (", length(genes), " genes)"),
           silent = TRUE)
  grid::grid.newpage()
  grid::grid.draw(ph$gtable)
  save_pheatmap(ph, file.path(RESULTS_DIR, "figures", filename), width = width, height = height)
  cat("  →", filename, "(", length(genes), "genes)\n\n")
}

