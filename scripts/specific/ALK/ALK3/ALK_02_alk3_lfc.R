compute_drug_lfc <- function(drug) {
  trt       <- trt_by_drug[[drug]]
  resistant <- resistant_by_drug[[drug]]
  expr_trt  <- if (length(trt) > 1) rowMeans(mat[, trt]) else mat[, trt]
  expr_res  <- if (length(resistant) > 1) rowMeans(mat[, resistant]) else mat[, resistant]

  lfc_res_vs_trt <- expr_res - expr_trt
  lfc_res_vs_unt <- expr_res - expr_unt
  lfc_trt_vs_unt <- expr_trt - expr_unt

  classification <- classify_lfc(lfc_res_vs_trt, LOGFC_THRESHOLD)
  ya_elevado_trt <- abs(lfc_trt_vs_unt) >= LOGFC_THRESHOLD

  tab <- table(classification)
  cat("  [", drug, "] Distribution:\n", sep = "")
  for (cls in names(tab)) {
    pct <- round(100 * tab[cls] / sum(tab), 1)
    cat("    ", cls, ":", tab[cls], "(", pct, "%)\n")
  }
  cat("    Already elevated in Treated (|LFC_Trt_vs_Unt| >=", LOGFC_THRESHOLD, "):", sum(ya_elevado_trt), "\n")

  tibble(
    Gene                  = rownames(mat),
    Drug                  = drug,
    LFC_Res_vs_Trt        = lfc_res_vs_trt,
    LFC_Res_vs_Unt        = lfc_res_vs_unt,
    LFC_Trt_vs_Unt        = lfc_trt_vs_unt,
    Mean_Expr_Unt         = expr_unt,
    Mean_Expr_Trt         = expr_trt,
    Mean_Expr_Res         = expr_res,
    Classification        = classification,
    Already_High_in_Treated = ya_elevado_trt
  )
}

