# scales are free because the Treated reference differs between arms.
label_genes_for_drug <- function(df_drug) {
  top15_up   <- df_drug %>% filter(Classification == "Upregulated") %>%
    arrange(desc(LFC_Res_vs_Trt)) %>% slice_head(n = 15) %>% pull(Gene)
  top15_down <- df_drug %>% filter(Classification == "Downregulated") %>%
    arrange(LFC_Res_vs_Trt) %>% slice_head(n = 15) %>% pull(Gene)
  core_hits  <- df_drug %>%
    filter(Classification %in% c("Upregulated", "Downregulated"), Gene %in% alk_resistance_core) %>%
    pull(Gene)
  unique(c(FORCED_GENES, core_hits, top15_up, top15_down))
}

