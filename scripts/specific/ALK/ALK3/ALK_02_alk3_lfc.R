# ============================================================
# ALK_02_alk3_lfc.R
# Purpose: LFC and gene classification (Upregulated/Downregulated/Other)
#   in COMBINED ALK3, computed PER DRUG. Derived from ALK_02_alk2_lfc.R.
#
# Unlike ALK1/ALK2 (1 drug -> 1 LFC per gene), ALK3 has 2
# drug arms that share the same untreated parental but differ in
# their treated parental (ALK3_L / ALK3_A) and their resistant lines (5 Lorlatinib +
# 3 Alectinib). The Res_vs_Trt/Res_vs_Unt LFC is computed PER DRUG (each
# resistant line against ITS OWN treated parental), and both results are
# combined in a single long table with a Drug column, same criterion as
# the combined SNV script of the WES analysis (intra/inter-drug comparison).
#
# Classification: only Upregulated/Downregulated/Other on LFC_Res_vs_Trt
# (the correct pharmacological comparator), instead of a 5-class scheme
# (Acquired/Pre_existing/Maintained/Downregulated/Other). "Pre_existing" in
# bulk RNA-seq (no subclone resolution) is weaker evidence than the
# pre-existence measured in scDNA-seq/scRNA-seq. The signal "this was already
# moving under acute treatment before resistance" is kept as an informative
# column (Already_High_in_Treated), not as a category of its own.
#
# Inputs (results/ALK/ALK3/tables/): 01_mat_tmm.csv, 01_metadata_unit.csv
#   (generated by ALK_01_alk3_qc.R); config/colors.R, config/gene_lists.R
# Outputs (results/ALK/ALK3/): tables/02_*.csv, figures/02_*.png,
#   report/02_lfc_report.md
# Usage: source(here::here("scripts/specific/ALK/ALK3/ALK_02_alk3_lfc.R"))
#   or Rscript from any folder of the repo.
# ============================================================
