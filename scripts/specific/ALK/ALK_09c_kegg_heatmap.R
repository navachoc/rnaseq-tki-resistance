plot_panel_kegg_combinado <- function(df_sub, titulo, rango_color, rango_count) {
  # Fixed Y axis order (by FoldEnrichment within the panel) so that the text
  # colour vector can be built in the SAME order.
  orden_desc <- df_sub %>% arrange(FoldEnrichment) %>% pull(Description) %>% unique()
  df_sub <- df_sub %>% mutate(Description = factor(Description, levels = orden_desc))
  color_por_nivel <- COLOR_N_MODOS[as.character(df_sub$N_modos[match(levels(df_sub$Description), df_sub$Description)])]
  color_por_nivel[is.na(color_por_nivel)] <- "grey30"

  # Upward triangle (Up) / downward triangle (Down) -- pch 24/25 are only
  # filled with "fill", not "colour" (which is kept for a fixed thin border).
  ggplot(df_sub, aes(x = FoldEnrichment, y = Description,
                      size = Count, fill = p.adjust, shape = Direction)) +
    geom_point(color = "grey20", stroke = 0.3) +
    # Invisible points only to generate the colour legend of the pathway name
    # (element_text does not generate its own legend) -- standard ggplot2
    # trick for legends of aesthetics not mapped to the visible geometry.
    geom_point(aes(colour = N_modos), alpha = 0, size = 0, show.legend = TRUE) +
    scale_fill_gradient(low = COLOR_KEGG_SIG, high = COLOR_KEGG_NOSIG, trans = "log10",
                         name = "p.adjust", limits = rango_color,
                         guide = guide_colorbar(reverse = TRUE, order = 3)) +
    scale_size_continuous(range = c(2, 8), name = "Genes", limits = rango_count,
                           guide = guide_legend(override.aes = list(shape = 24, fill = "grey40"), order = 2)) +
    scale_shape_manual(values = c(Upregulated = 24, Downregulated = 25), name = "Direction",
                        guide = guide_legend(order = 1)) +
    scale_colour_manual(values = COLOR_N_MODOS, name = "Convergence\n(n comparators)", drop = FALSE,
                         guide = guide_legend(order = 4, override.aes = list(alpha = 1, size = 3, shape = 15))) +
    labs(title = titulo, x = "Fold enrichment", y = NULL) +
    theme_minimal(base_size = 10) +
    theme(
      axis.text.y  = element_text(size = 7.5, colour = color_por_nivel, face = "bold"),
      plot.title   = element_text(face = "bold", size = 11),
      legend.position = "right",
      legend.box   = "vertical",
      panel.background = element_rect(fill = "white"),
      plot.background  = element_rect(fill = "white")
    )
}

paneles_kegg_combinado <- lapply(facetas, function(f) {
  df_f <- kegg_top %>% filter(Faceta == f)
  plot_panel_kegg_combinado(df_f, as.character(f), range(df_f$p.adjust), range(df_f$Count))
})

