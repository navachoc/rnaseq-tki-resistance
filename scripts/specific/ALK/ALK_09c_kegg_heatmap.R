# The geneID column of the KEGG tables holds numeric Entrez IDs (e.g.
# "1870/991/1031..."), NOT gene symbols -- checked directly against the
# CSV, whereas the resistance signature uses symbols ("PSG5", "H2AC19"...).
# Without this conversion the intersection with Gene is empty.
entrez_a_symbol <- function(entrez_ids) {
  entrez_ids <- unique(entrez_ids)
  if (length(entrez_ids) == 0) return(character(0))
  simbolos <- suppressMessages(AnnotationDbi::mapIds(
    org.Hs.eg.db, keys = entrez_ids, column = "SYMBOL", keytype = "ENTREZID"
  ))
  unname(simbolos[!is.na(simbolos)])
}

# RUTAS_FINALES_KEGG is already loaded (section 2, above -- Panel D-G uses
# the same object, a single CSV read for the whole script).

# Member genes of the final KEGG pathways of this facet. The geneID is read
# from the specific table of the LFC mode(s) in which the pathway was
# significant (Modos_sig column, e.g. "combinado+vs_no_tratada"), union of
# all of them -- a pathway can be supported in more than one mode, and the
# genes that contributed to significance in any of them are taken. Files
# generated by ALK_09b_kegg_vs_untreated_exploratory.R.
genes_rutas_importantes_facet <- function(faceta) {
  slug <- tolower(gsub("[^A-Za-z0-9]+", "_", faceta))
  carpeta <- if (grepl("^ALK3", faceta)) "ALK3" else faceta
  rutas_faceta <- RUTAS_FINALES_KEGG[RUTAS_FINALES_KEGG$Faceta == faceta, ]
  if (nrow(rutas_faceta) == 0) return(character(0))

  entrez_ids <- unlist(lapply(seq_len(nrow(rutas_faceta)), function(i) {
    fila <- rutas_faceta[i, ]
    direccion <- tolower(fila$Direction)
    modos <- strsplit(fila$Modos_sig, "\\+")[[1]]
    unlist(lapply(modos, function(modo) {
      ruta_csv <- here::here("results", "ALK", carpeta, "tables",
                             sprintf("04_kegg_%s_%s_%s.csv", direccion, modo, slug))
      if (!file.exists(ruta_csv)) return(character(0))
      df <- read.csv(ruta_csv, stringsAsFactors = FALSE)
      df <- df[df$Description == fila$Description, ]
      if (nrow(df) == 0) return(character(0))
      unlist(strsplit(df$geneID, "/"))
    }))
  }))
  entrez_a_symbol(entrez_ids)
}

# Threshold identical to classify_lfc()/ALK_02_*_lfc.R (LOGFC_THRESHOLD=2.0).
# Classification/AbsLFC use LFC_Res_vs_Unt -- it makes no sense to rank "the
# most striking" or filter the candidate universe with a metric different
# from the one plotted by Panel A itself (vs untreated).
LOGFC_THRESHOLD_FIG2 <- 2.0

# "Striking" genes without an assigned RUTAS_IMPORTANTES pathway, excluded
# on purpose to leave room for forced pathway genes (manually curated
# list). Defined before candidatos_fig2 (used in its filter).
# MMP1 is replaced by ROS1 (see GENES_LLAMATIVOS_FORZADOS below), a
# candidate for RTK bypass in ALK2 (same family as ALK). ABCA8 is
# replaced by AXL, a striking finding in ALK3 (RTK of TKI resistance
# widely cited in the literature, here downregulated instead of
# upregulated, an unexpected direction).
GENES_LLAMATIVOS_EXCLUIDOS <- c("LCN2", "S100A9", "S100P", "KRT6A", "MUC5B",
                                 "MUC5AC", "HMMR", "H2AC19", "MMP1", "ABCA8", "OLFM1",
                                 "MIR205HG", "FLNC", "SERPINB9")

# "Striking" genes forced to enter despite not being among the top
# N_LLAMATIVOS_MAX by AbsLFC -- ROS1 (LFC_Res_vs_Unt=6.88 in ALK2) replaces
# MMP1 (LFC=7.42, now in GENES_LLAMATIVOS_EXCLUIDOS). AXL
# (LFC_Res_vs_Unt=-6.50 in ALK3-Lorlatinib) replaces ABCA8 (LFC=7.72).
# CACNA1G (LFC_Res_vs_Unt=5.43 in ALK3-Alectinib, opposite pattern to
# Lorlatinib where it decreases) replaces OLFM1 (LFC=7.39). SPP1, C3 and
# AKR1B10 (opposite Lorlatinib/Alectinib pattern in ALK3, AKR1B10 a real
# member of Pentose and glucuronate interconversions) replace
# MIR205HG/FLNC/SERPINB9. Manually curated list.
GENES_LLAMATIVOS_FORZADOS <- c("ROS1", "AXL", "CACNA1G", "SPP1", "C3", "AKR1B10")

# Weakest "important" genes (top KEGG) of the pool -- discarded on
# purpose to leave room for COL4A3/LAMA4 (the most convergent genes of the
# whole list, 10 and 5 pathways respectively, see GENES_IMPORTANTES_
# FORZADOS). Manually curated list.
GENES_IMPORTANTES_EXCLUIDOS <- c("IL6", "BMP4")

# "Important" genes forced into the final selection despite not falling
# within the pure AbsLFC cut -- COL4A3 (10 pathways) and LAMA4 (5
# pathways) are the most convergent genes of the whole list and are
# prioritised over the rest; PGF/PTGER1/PRSS3 fill the gap left by
# GENES_IMPORTANTES_EXCLUIDOS. Manually curated list.
GENES_IMPORTANTES_FORZADOS <- c("COL4A3", "LAMA4", "PGF", "PTGER1", "PRSS3")

# Candidates = genes Up/Down by LFC_Res_vs_Unt (not the precomputed
# Classification column, which follows vs_tratada) of the 4 facets,
# collapsed to 1 row per gene (max |LFC| across facets, Importante if it is
# in any). Same 2 quality filters as the rest of the scripts: drop IDs
# without interpretation (ENSG* / dot-containing) and minimum detectable
# expression in Treated or Resistant; restricted to common_genes_full
# (present in the 3 TMM matrices).
candidatos_fig2 <- bind_rows(lapply(RUTAS_FIRMA, function(e) {
  df <- read.csv(e$ruta, stringsAsFactors = FALSE)
  if (!is.null(e$drug)) df <- df %>% filter(Drug == e$drug)
  pool_importante <- genes_rutas_importantes_facet(e$faceta)
  df %>%
    filter(abs(LFC_Res_vs_Unt) > LOGFC_THRESHOLD_FIG2) %>%
    filter(!grepl("^ENSG", Gene), !grepl("\\.", Gene)) %>%
    filter(Mean_Expr_Trt > 0 | Mean_Expr_Res > 0) %>%
    filter(Gene %in% common_genes_full) %>%
    filter(!Gene %in% c(GENES_LLAMATIVOS_EXCLUIDOS, GENES_IMPORTANTES_EXCLUIDOS)) %>%
    transmute(Gene, AbsLFC = abs(LFC_Res_vs_Unt), Importante = Gene %in% pool_importante)
})) %>%
  group_by(Gene) %>%
  summarise(AbsLFC = max(AbsLFC), Importante = any(Importante), .groups = "drop")

# Striking genes FIRST (10, any gene of the pool by AbsLFC, whether or not it
# belongs to an important pathway). GENES_LLAMATIVOS_FORZADOS always enter
# when available, the rest of the quota is filled by descending AbsLFC.
llamativos_forzados_presentes <- candidatos_fig2 %>%
  filter(Gene %in% GENES_LLAMATIVOS_FORZADOS)
huecos_llamativos <- max(0, N_LLAMATIVOS_MAX - nrow(llamativos_forzados_presentes))
seleccion_llamativos <- bind_rows(
  llamativos_forzados_presentes,
  candidatos_fig2 %>%
    filter(!Gene %in% GENES_LLAMATIVOS_FORZADOS) %>%
    arrange(desc(AbsLFC)) %>%
    slice_head(n = huecos_llamativos)
)

# Pathway genes fill the rest of the quota up to TOTAL_MAX_GENES.
# GENES_IMPORTANTES_FORZADOS (COL4A3/LAMA4/PGF/PTGER1/PRSS3) ALWAYS enter
# when available, prioritised over the rest -- the rest of the quota is
# filled by descending AbsLFC.
huecos_rutas <- max(0, TOTAL_MAX_GENES - nrow(seleccion_llamativos))
pool_importantes_disponibles <- candidatos_fig2 %>%
  filter(Importante, !Gene %in% seleccion_llamativos$Gene)
