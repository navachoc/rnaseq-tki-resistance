lfc_gen_si_existe <- function(mat, gen, untreated_col, target_cols) {
  if (!gen %in% rownames(mat)) return(setNames(rep(NA_real_, length(target_cols)), target_cols))
  lfc_vs_untreated(mat, gen, untreated_col, target_cols)[1, ]
}

lfc_gen_extendido <- function(mat_log2cpm, gen, untreated_col, target_cols) {
  if (!gen %in% rownames(mat_log2cpm)) return(setNames(rep(NA_real_, length(target_cols)), target_cols))
  lfc_vs_untreated(mat_log2cpm, gen, untreated_col, target_cols)[1, ]
}

