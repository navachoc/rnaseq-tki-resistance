# Total raw count per gene/line -- same criterion that discarded the gene
# in the original pipeline (sum of reads of ALL samples of that line
# < MIN_COUNT), used only to flag which cells are "not detected".
conteo_total_forzado <- function(counts_file, cell_line, genes_forzados) {
  counts <- leer_counts_crudos(counts_file, cell_line)
  genes_presentes <- intersect(genes_forzados, rownames(counts))
  totales <- setNames(rep(0, length(genes_forzados)), genes_forzados)
  totales[genes_presentes] <- rowSums(counts[genes_presentes, , drop = FALSE])
  totales
}

