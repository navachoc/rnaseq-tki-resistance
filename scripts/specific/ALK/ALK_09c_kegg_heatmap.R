leer_counts_crudos <- function(counts_file, cell_line = NULL) {
  meta_file <- sub("counts_", "metadata_", counts_file)
  sep <- if (grepl(";", readLines(counts_file, n = 1))) ";" else ","
  counts   <- read.csv(counts_file, sep = sep, check.names = FALSE)
  metadata <- read.csv(meta_file,   sep = sep)
  rownames(counts) <- make.names(counts[, 2], unique = TRUE)
  counts <- counts[, -c(1:3)]
  sample_to_model <- setNames(metadata$Model, metadata$Sample)
  colnames(counts) <- sample_to_model[colnames(counts)]
  rownames(metadata) <- metadata$Model
  if (!is.null(cell_line)) {
    metadata_unit <- metadata %>% filter(Cell_Line == cell_line)
    counts <- counts[, rownames(metadata_unit), drop = FALSE]
  }
  counts
}

# Recompute log2CPM (TMM) of genes_forzados forcing their entry into the
# minimum expression filter -- identical to ALK_01_*_qc.R except for the OR
# with genes_forzados in the `keep` vector.
extender_log2cpm_forzado <- function(counts_file, cell_line, genes_forzados, min_count) {
  counts <- leer_counts_crudos(counts_file, cell_line)
  keep <- rowSums(counts) >= min_count | rownames(counts) %in% genes_forzados
  dge  <- edgeR::DGEList(counts = counts[keep, ])
  dge  <- edgeR::calcNormFactors(dge, method = "TMM")
  mat  <- edgeR::cpm(dge, log = TRUE, prior.count = 1)
  mat[intersect(genes_forzados, rownames(mat)), , drop = FALSE]
}

log2cpm_alk1_forzado <- extender_log2cpm_forzado(
