leer_tmm <- function(cell_line) {
  ruta <- here::here("results", "ALK", cell_line, "tables", "01_mat_tmm.csv")
  df <- read.csv(ruta, check.names = FALSE)
  rownames(df) <- df$Gene
  as.matrix(df[, -1, drop = FALSE])
}

