# Retrieve FoldEnrichment/Count/p.adjust of the pathway from the table of the
# mode that gave the minimum p.adjust (the same value already recorded as
# p.adjust_min when building the convergence ranking) -- consistent with
# genes_rutas_importantes_facet() below, same source files.
recuperar_stats_ruta_kegg <- function(faceta, direccion, descripcion, modos_sig) {
  slug    <- tolower(gsub("[^A-Za-z0-9]+", "_", faceta))
  carpeta <- if (grepl("^ALK3", faceta)) "ALK3" else faceta
  modos   <- strsplit(modos_sig, "\\+")[[1]]
  filas <- bind_rows(lapply(modos, function(modo) {
    ruta_csv <- here::here("results", "ALK", carpeta, "tables",
                           sprintf("04_kegg_%s_%s_%s.csv", tolower(direccion), modo, slug))
    if (!file.exists(ruta_csv)) return(NULL)
    df <- read.csv(ruta_csv, stringsAsFactors = FALSE)
    df[df$Description == descripcion, c("p.adjust", "Count", "FoldEnrichment")]
  }))
  if (is.null(filas) || nrow(filas) == 0) return(NULL)
  filas %>% arrange(p.adjust) %>% slice_head(n = 1)
}

kegg_top <- bind_rows(lapply(seq_len(nrow(RUTAS_FINALES_KEGG)), function(i) {
  fila  <- RUTAS_FINALES_KEGG[i, ]
  stats <- recuperar_stats_ruta_kegg(fila$Faceta, fila$Direction, fila$Description, fila$Modos_sig)
  if (is.null(stats)) return(NULL)
  data.frame(Faceta = fila$Faceta, Direction = fila$Direction, Description = fila$Description,
             p.adjust = stats$p.adjust, Count = stats$Count, FoldEnrichment = stats$FoldEnrichment,
             Modos_sig = fila$Modos_sig, stringsAsFactors = FALSE)
}))

