# Colours of the pathway NAME (Y axis) according to IN HOW MANY LFC
# comparators (of the 3: vs_no_tratada/vs_tratada/combinado) it was
# significant -- not which ones specifically, only the convergence number
# (1/2/3). The point itself still shows FoldEnrichment/Count/p.adjust exactly
