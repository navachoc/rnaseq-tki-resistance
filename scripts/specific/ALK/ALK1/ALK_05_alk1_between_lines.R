# ============================================================
# ALK_05_alk1_between_lines.R
# Purpose: comparison between the resistant populations of ALK1 (L1, L2, L3).
#   Scripts 02/03/04 compare each resistant line with the treated parental;
#   this one answers a different question, how the 3 resistant
#   populations differ FROM EACH OTHER. RNA-seq equivalent of the clonal
#   heterogeneity seen in MAFtools/WES (inferHeterogeneity).
#
# With a single sample per line (no technical replicates) there is no power for
# a formal per-line statistical test, so direct LFC is used
# (Li vs mean of the other 2) and variance across the 3, not p-values.
# Inputs (results/ALK/ALK1/tables/): 01_mat_tmm.csv, 01_metadata_unit.csv
#   (generated by ALK_01_alk1_qc.R); config/colors.R, config/gene_lists.R
# Outputs (results/ALK/ALK1/): tables/05_*.csv, figures/05_*.png,
#   report/05_between_lines_report.md
# Usage: source(here::here("scripts/specific/ALK/ALK1/ALK_05_alk1_between_lines.R"))
#   or Rscript from any folder of the repo.
# ============================================================
CELL_LINE <- "ALK1"
DRUG      <- "Lorlatinib"
RECEPTOR  <- "ALK"
LOGFC_THRESHOLD  <- 2.0
TOP_N_VARIANZA   <- 50   # most variable genes between L1/L2/L3 for the heatmap
# ============================================================
RESULTS_DIR <- here::here("results", RECEPTOR, CELL_LINE)
CONFIG_DIR  <- here::here("config")
source(file.path(CONFIG_DIR, "colors.R"))
source(file.path(CONFIG_DIR, "gene_lists.R"))

OUT_PREFIX <- paste0(CELL_LINE, "_", DRUG)

# Forced genes, as in ALK_02/ALK_03 -- driver fusion, always visible
FORCED_GENES <- c("ALK", "EML4")

GRADIENTE_RNA <- c("#000000", "#808080", "#f2a900")
heatmap_expr  <- colorRampPalette(GRADIENTE_RNA)(100)

# LIBRARIES ------------------------------------------------------------------
library(ggplot2)
library(ggrepel)
library(pheatmap)
library(dplyr)
library(tidyr)

cal_zscore <- function(x) if (sd(x) == 0) rep(0, length(x)) else (x - mean(x)) / sd(x)

save_pheatmap <- function(ph, filepath, width, height, res = 300) {
  png(filepath, width = width, height = height, units = "in", res = res)
  if (!is.null(ph$gtable)) {
    grid::grid.draw(ph$gtable)
  } else {
    grid::grid.newpage()
    grid::grid.draw(ph)
  }
  dev.off()
}

cat("\n================================================================\n")
cat("  BETWEEN RESISTANT LINES —", OUT_PREFIX, "\n")
cat("================================================================\n\n")

# LOAD TABLES FROM ALK_01_alk1_qc.R ------------------------------------------
mat_file  <- file.path(RESULTS_DIR, "tables", "01_mat_tmm.csv")
meta_file <- file.path(RESULTS_DIR, "tables", "01_metadata_unit.csv")

if (!file.exists(mat_file)) stop("01_mat_tmm.csv not found — run ALK_01_alk1_qc.R first")

mat_df        <- read.csv(mat_file, check.names = FALSE)
rownames(mat_df) <- mat_df$Gene
mat           <- as.matrix(mat_df[, -1])

meta_df       <- read.csv(meta_file, check.names = FALSE)
rownames(meta_df) <- meta_df$Model
metadata_unit <- meta_df[, -1]

resistant <- rownames(metadata_unit)[metadata_unit$Condition == "Resistance"]
if (length(resistant) < 2) stop("At least 2 resistant lines are needed to compare with each other.")
cat("1. Resistant lines:", paste(resistant, collapse = ", "), "\n\n")

mat_res <- mat[, resistant, drop = FALSE]

# STEP 1: CORRELATION / DISTANCE BETWEEN LINES --------------------------------
cat("2. Correlation and distance between resistant lines...\n")

cor_mat <- cor(mat_res, method = "pearson")
cat("  Pearson correlation (log2CPM, all genes):\n")
print(round(cor_mat, 3))
cat("\n")
write.csv(as.data.frame(cor_mat) %>% tibble::rownames_to_column("Model"),
          file.path(RESULTS_DIR, "tables", "05_correlation_between_lines.csv"), row.names = FALSE)

dist_mat <- as.matrix(dist(t(mat_res)))
ann_res  <- metadata_unit[resistant, c("Condition", "Treatment"), drop = FALSE]
ann_colors_res <- filter_annotation_colors(ann_res)

ph_dist <- pheatmap(dist_mat,
         clustering_distance_rows = as.dist(dist_mat),
         clustering_distance_cols = as.dist(dist_mat),
         color          = heatmap_expr,
         annotation_col = ann_res,
         annotation_colors = ann_colors_res,
         main           = paste("Distances between resistant lines —", OUT_PREFIX),
         silent         = TRUE)
grid::grid.newpage()
grid::grid.draw(ph_dist$gtable)
save_pheatmap(ph_dist, file.path(RESULTS_DIR, "figures", "05_distances_between_lines.png"),
              width = 6, height = 5.5)
cat("  → 05_distances_between_lines.png\n\n")

# STEP 2: LFC PER LINE (Li vs mean of the other 2) --------------------------
cat("3. LFC per line (Li vs mean of the other 2 resistant)...\n")

classify_lfc <- function(lfc, threshold) {
  cls <- rep("Other", length(lfc))
  cls[lfc >  threshold] <- "Upregulated"
  cls[lfc < -threshold] <- "Downregulated"
  cls
}

lfc_per_line <- lapply(resistant, function(li) {
  otras <- setdiff(resistant, li)
  expr_li     <- mat_res[, li]
  expr_otras  <- if (length(otras) > 1) rowMeans(mat_res[, otras]) else mat_res[, otras]
  lfc         <- expr_li - expr_otras
  tibble::tibble(
    Gene           = rownames(mat_res),
    Model          = li,
    LFC_vs_others   = lfc,
    Mean_Expr_Li   = expr_li,
    Mean_Expr_Others = expr_otras,
    Classification = classify_lfc(lfc, LOGFC_THRESHOLD)
  )
}) %>% bind_rows()

write.csv(lfc_per_line, file.path(RESULTS_DIR, "tables", "05_lfc_per_line.csv"), row.names = FALSE)

tab_per_line <- lfc_per_line %>% count(Model, Classification) %>%
  tidyr::pivot_wider(names_from = Classification, values_from = n, values_fill = 0)
cat("  Distinctive genes per line (|LFC| >=", LOGFC_THRESHOLD, "versus the other 2):\n")
print(as.data.frame(tab_per_line))
cat("\n")

# Distinctive genes: those that ONLY one line has beyond the threshold (Up or Down)
# -- if 2+ lines share the same gene beyond the threshold, it is not really
# distinctive of a single line, it is a trend shared between 2 of the 3.
distinctive <- lfc_per_line %>%
  filter(Classification != "Other") %>%
  group_by(Gene) %>%
  filter(n() == 1) %>%
  ungroup() %>%
  arrange(Model, desc(abs(LFC_vs_others)))

write.csv(distinctive, file.path(RESULTS_DIR, "tables", "05_distinctive_genes_per_line.csv"), row.names = FALSE)
cat("  Distinctive genes of a single line (not shared):", nrow(distinctive), "\n")
for (li in resistant) {
  n_li <- sum(distinctive$Model == li)
  cat("    ", li, ":", n_li, "\n")
}
cat("\n")

# Cross-reference with alk_resistance_core and wes_panel_alk (same criterion as ALK_03)
cat("4. Cross-referencing distinctive genes with alk_resistance_core and wes_panel_alk...\n")
distinctive_core <- distinctive %>% filter(Gene %in% alk_resistance_core)
distinctive_wes  <- distinctive %>% filter(Gene %in% wes_panel_alk)
cat("  alk_resistance_core:", paste0(distinctive_core$Gene, " [", distinctive_core$Model, "]", collapse = ", "), "\n")
cat("  wes_panel_alk:      ", paste0(distinctive_wes$Gene,  " [", distinctive_wes$Model,  "]", collapse = ", "), "\n\n")
write.csv(distinctive_wes, file.path(RESULTS_DIR, "tables", "05_distinctive_genes_wes_panel.csv"), row.names = FALSE)

# STEP 3: PAIRED SCATTERS (L1 vs L2, L1 vs L3, L2 vs L3...) -----------------
cat("5. Paired scatters between lines...\n")

pares <- combn(resistant, 2, simplify = FALSE)
for (par in pares) {
  a <- par[1]; b <- par[2]
  df_ab <- tibble::tibble(
    Gene = rownames(mat_res),
    A    = mat_res[, a],
    B    = mat_res[, b]
  ) %>%
    mutate(
      Diff  = A - B,
      label = ifelse(Gene %in% FORCED_GENES | abs(Diff) > LOGFC_THRESHOLD * 1.5, Gene, "")
    )
  r_val <- round(cor(df_ab$A, df_ab$B), 3)

  p_pair <- ggplot(df_ab, aes(A, B)) +
    geom_point(alpha = 0.3, size = 0.7, color = "#555555") +
    geom_abline(slope = 1, intercept = 0, linetype = "dashed", color = "gray50") +
    geom_text_repel(aes(label = label), size = 2.5, max.overlaps = 20,
                    segment.size = 0.2, box.padding = 0.3, color = "#e67e22", seed = 1) +
    labs(
      title = paste0("Expression ", a, " vs ", b, " — ", OUT_PREFIX),
      subtitle = paste("Pearson r =", r_val),
      x = paste("log2CPM —", a), y = paste("log2CPM —", b)
    ) +
    theme_minimal(base_size = 12) +
    theme(plot.title = element_text(face = "bold"),
          panel.background = element_rect(fill = "white"),
          plot.background  = element_rect(fill = "white"))

  fname <- paste0("05_scatter_", a, "_vs_", b, ".png")
  ggsave(file.path(RESULTS_DIR, "figures", fname), p_pair, width = 8, height = 7, dpi = 300)
  cat("  →", fname, "(r =", r_val, ")\n")
}
cat("\n")

# STEP 4: HEATMAP OF MOST VARIABLE GENES BETWEEN LINES + DISTINCTIVE + FORCED ---
cat("6. Heatmap of most variable genes between L1/L2/L3...\n")

var_res    <- apply(mat_res, 1, var)
top_var    <- names(sort(var_res, decreasing = TRUE))[seq_len(min(TOP_N_VARIANZA, length(var_res)))]
genes_hm   <- union(FORCED_GENES, top_var)
genes_hm   <- genes_hm[genes_hm %in% rownames(mat)]

z_mat <- t(apply(mat[genes_hm, resistant, drop = FALSE], 1, cal_zscore))
ann_colors_res2 <- filter_annotation_colors(ann_res)

ph_var <- pheatmap(z_mat,
         color             = heatmap_expr,
         show_rownames     = (length(genes_hm) <= 60),
         show_colnames     = TRUE,
         fontsize_row      = 7,
         annotation_col    = ann_res,
         annotation_colors = ann_colors_res2,
         cluster_rows      = TRUE,
         cluster_cols      = TRUE,
         clustering_method = "ward.D2",
         main = paste0("Top ", length(top_var), " most variable genes between lines + forced — ", OUT_PREFIX),
         silent = TRUE)
grid::grid.newpage()
grid::grid.draw(ph_var$gtable)
save_pheatmap(ph_var, file.path(RESULTS_DIR, "figures", "05_heatmap_variable_between_lines.png"),
              width = 8, height = 10)
cat("  → 05_heatmap_variable_between_lines.png (", length(genes_hm), "genes)\n\n")

