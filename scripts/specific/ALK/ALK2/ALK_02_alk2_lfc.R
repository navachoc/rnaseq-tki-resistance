# ============================================================
# ALK_02_alk2_lfc.R
# Purpose: LFC and gene classification (Upregulated/Downregulated/Other)
#   in ALK2. Main comparator LFC_Res_vs_Trt (resistant versus the
#   acutely treated parental), threshold |LFC| >= LOGFC_THRESHOLD.
#   Dedicated per-model version, derived from scripts/simple/rna_02.1_lfc.R.
#
# Classification: only Upregulated/Downregulated/Other on LFC_Res_vs_Trt
# (the correct pharmacological comparator), instead of a 5-class scheme
# (Acquired/Pre_existing/Maintained/Downregulated/Other). "Pre_existing" in
# bulk RNA-seq (no subclone resolution) is weaker evidence than the
# pre-existence measured in scDNA-seq/scRNA-seq, and using the same word
# for both could be confusing. The signal "this was already moving under
# acute treatment before resistance" is kept as an informative column
# (Ya_Elevado_en_Treated), not as a category with its own name.
#
# Inputs (results/ALK/ALK2/tables/): 01_mat_tmm.csv, 01_metadata_unit.csv
#   (generated by ALK_01_alk2_qc.R); config/colors.R, config/gene_lists.R
# Outputs (results/ALK/ALK2/): tables/02_lfc_master_table.csv,
#   tables/02_classified_genes.csv, figures/02_*.png, report/02_lfc_report.md
# Usage: source(here::here("scripts/specific/ALK/ALK2/ALK_02_alk2_lfc.R"))
#   or Rscript from any folder of the repo.
# ============================================================
CELL_LINE       <- "ALK2"
DRUG            <- "Lorlatinib"
RECEPTOR        <- "ALK"
LOGFC_THRESHOLD <- 2.0
# ============================================================
RESULTS_DIR <- here::here("results", RECEPTOR, CELL_LINE)
CONFIG_DIR  <- here::here("config")
source(file.path(CONFIG_DIR, "colors.R"))
source(file.path(CONFIG_DIR, "gene_lists.R"))

OUT_PREFIX <- paste0(CELL_LINE, "_", DRUG)

# Genes forced in ALL the figures of this script, whether or not they pass the
# LFC filter — ALK and EML4 are the two genes of the driver fusion, always
# relevant to see regardless of whether their overall expression changes with the LFC.
FORCED_GENES <- c("ALK", "EML4")

GRADIENTE_RNA <- c("#000000", "#808080", "#f2a900")
heatmap_expr  <- colorRampPalette(GRADIENTE_RNA)(100)

# LIBRARIES ------------------------------------------------------------------
library(ggplot2)
library(ggrepel)
library(pheatmap)
library(dplyr)
library(tibble)

save_pheatmap <- function(ph, filepath, width, height, res = 300) {
  png(filepath, width = width, height = height, units = "in", res = res)
  if (!is.null(ph$gtable)) {
    grid::grid.draw(ph$gtable)
  } else {
    grid::grid.newpage()
    grid::grid.draw(ph)
  }
  dev.off()
}

cal_zscore <- function(x) if (sd(x) == 0) rep(0, length(x)) else (x - mean(x)) / sd(x)

# Simple classification: only the direction of the Res vs Trt change, without
# distinguishing when the change appeared (that signal goes apart, see Ya_Elevado_en_Treated).
classify_lfc <- function(lfc, threshold) {
  cls <- rep("Other", length(lfc))
  cls[lfc >  threshold] <- "Upregulated"
  cls[lfc < -threshold] <- "Downregulated"
  cls
}

