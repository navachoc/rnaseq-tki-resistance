# ============================================================
# ALK_05_alk2_between_lines.R
# Purpose: comparison between the resistant populations of ALK2 (L1-L5).
#   Scripts 02/03/04 compare each resistant line with the treated parental;
#   this one answers a different question, how the 5 resistant
#   populations differ FROM EACH OTHER. RNA-seq equivalent of the clonal
#   heterogeneity seen in MAFtools/WES (inferHeterogeneity).
#
# ALK2 has a phenotypic partition known from the MTT assay: L1, L4 and L5
# shifted their IC50 (3.6-61.38x), but L2 and L3 did not (IC50 equal to the
# parental) despite having tolerated the same final drug concentration.
# Besides the generic per-individual-line analysis (same as
# ALK_05_alk1_between_lines.R), this script adds a comparison by
# GROUP (L1/L4/L5 vs L2/L3) to look for what explains that difference.
#
# With a single sample per line (no technical replicates) there is no power for
# a formal statistical test, so direct LFC and variance are used, not
# p-values.
# Inputs (results/ALK/ALK2/tables/): 01_mat_tmm.csv, 01_metadata_unit.csv
#   (generated by ALK_01_alk2_qc.R); config/colors.R, config/gene_lists.R
# Outputs (results/ALK/ALK2/): tables/05_*.csv, figures/05_*.png,
#   report/05_between_lines_report.md
# Usage: source(here::here("scripts/specific/ALK/ALK2/ALK_05_alk2_between_lines.R"))
#   or Rscript from any folder of the repo.
# ============================================================
CELL_LINE <- "ALK2"
DRUG      <- "Lorlatinib"
RECEPTOR  <- "ALK"
LOGFC_THRESHOLD  <- 2.0
TOP_N_VARIANZA   <- 50   # most variable genes between lines for the general heatmap
TOP_N_GRUPO      <- 50   # most distinctive genes for the L1/L4/L5 vs L2/L3 heatmap

# Phenotypic partition known from MTT — shifted vs unshifted IC50
GRUPOS_IC50 <- list(
  IC50_desplazado    = c("ALK2_L1", "ALK2_L4", "ALK2_L5"),
  IC50_sin_desplazar = c("ALK2_L2", "ALK2_L3")
)
# ============================================================
RESULTS_DIR <- here::here("results", RECEPTOR, CELL_LINE)
CONFIG_DIR  <- here::here("config")
source(file.path(CONFIG_DIR, "colors.R"))
source(file.path(CONFIG_DIR, "gene_lists.R"))

OUT_PREFIX <- paste0(CELL_LINE, "_", DRUG)

# Forced genes, as in ALK_02/ALK_03 -- driver fusion, always visible
FORCED_GENES <- c("ALK", "EML4")

GRADIENTE_RNA <- c("#000000", "#808080", "#f2a900")
heatmap_expr  <- colorRampPalette(GRADIENTE_RNA)(100)

# LIBRARIES ------------------------------------------------------------------
library(ggplot2)
library(ggrepel)
library(pheatmap)
library(dplyr)
library(tidyr)

cal_zscore <- function(x) if (sd(x) == 0) rep(0, length(x)) else (x - mean(x)) / sd(x)

save_pheatmap <- function(ph, filepath, width, height, res = 300) {
  png(filepath, width = width, height = height, units = "in", res = res)
  if (!is.null(ph$gtable)) {
    grid::grid.draw(ph$gtable)
  } else {
    grid::grid.newpage()
    grid::grid.draw(ph)
  }
  dev.off()
}

classify_lfc <- function(lfc, threshold) {
  cls <- rep("Other", length(lfc))
  cls[lfc >  threshold] <- "Upregulated"
  cls[lfc < -threshold] <- "Downregulated"
  cls
}

cat("\n================================================================\n")
cat("  BETWEEN RESISTANT LINES —", OUT_PREFIX, "\n")
cat("================================================================\n\n")

# LOAD TABLES FROM ALK_01_alk2_qc.R ------------------------------------------
mat_file  <- file.path(RESULTS_DIR, "tables", "01_mat_tmm.csv")
meta_file <- file.path(RESULTS_DIR, "tables", "01_metadata_unit.csv")

if (!file.exists(mat_file)) stop("01_mat_tmm.csv not found — run ALK_01_alk2_qc.R first")

mat_df        <- read.csv(mat_file, check.names = FALSE)
rownames(mat_df) <- mat_df$Gene
mat           <- as.matrix(mat_df[, -1])

meta_df       <- read.csv(meta_file, check.names = FALSE)
rownames(meta_df) <- meta_df$Model
metadata_unit <- meta_df[, -1]

resistant <- rownames(metadata_unit)[metadata_unit$Condition == "Resistance"]
if (length(resistant) < 2) stop("At least 2 resistant lines are needed to compare with each other.")
cat("1. Resistant lines:", paste(resistant, collapse = ", "), "\n\n")

grupo_check <- setdiff(unlist(GRUPOS_IC50), resistant)
if (length(grupo_check) > 0) {
  stop("GRUPOS_IC50 mentions lines that are not in metadata_unit: ", paste(grupo_check, collapse = ", "))
}

mat_res <- mat[, resistant, drop = FALSE]

# STEP 1: CORRELATION / DISTANCE BETWEEN LINES --------------------------------
cat("2. Correlation and distance between resistant lines...\n")

cor_mat <- cor(mat_res, method = "pearson")
cat("  Pearson correlation (log2CPM, all genes):\n")
print(round(cor_mat, 3))
cat("\n")
write.csv(as.data.frame(cor_mat) %>% tibble::rownames_to_column("Model"),
          file.path(RESULTS_DIR, "tables", "05_correlation_between_lines.csv"), row.names = FALSE)

dist_mat <- as.matrix(dist(t(mat_res)))
ann_res  <- metadata_unit[resistant, c("Condition", "Treatment"), drop = FALSE]
# IC50 group as an additional annotation -- useful to see whether the clustering
# already separates by phenotype before looking at any specific gene
ann_res$IC50_Group <- sapply(rownames(ann_res), function(m) {
  if (m %in% GRUPOS_IC50$IC50_desplazado) "Shifted" else "Unshifted"
})
ann_colors_res <- filter_annotation_colors(ann_res[, c("Condition", "Treatment"), drop = FALSE])
ann_colors_res$IC50_Group <- c(Shifted = "#2ecc71", Unshifted = "#e74c3c")

ph_dist <- pheatmap(dist_mat,
         clustering_distance_rows = as.dist(dist_mat),
         clustering_distance_cols = as.dist(dist_mat),
         color          = heatmap_expr,
         annotation_col = ann_res,
         annotation_colors = ann_colors_res,
         main           = paste("Distances between resistant lines —", OUT_PREFIX),
         silent         = TRUE)
grid::grid.newpage()
grid::grid.draw(ph_dist$gtable)
save_pheatmap(ph_dist, file.path(RESULTS_DIR, "figures", "05_distances_between_lines.png"),
              width = 6.5, height = 5.5)
cat("  → 05_distances_between_lines.png (with IC50_Group annotation)\n\n")

# STEP 2: LFC PER LINE (Li vs mean of the others) ----------------------------
cat("3. LFC per line (Li vs mean of the other", length(resistant) - 1, "resistant)...\n")

lfc_per_line <- lapply(resistant, function(li) {
  otras <- setdiff(resistant, li)
  expr_li     <- mat_res[, li]
  expr_otras  <- if (length(otras) > 1) rowMeans(mat_res[, otras]) else mat_res[, otras]
  lfc         <- expr_li - expr_otras
  tibble::tibble(
    Gene           = rownames(mat_res),
    Model          = li,
    LFC_vs_others   = lfc,
    Mean_Expr_Li   = expr_li,
    Mean_Expr_Others = expr_otras,
    Classification = classify_lfc(lfc, LOGFC_THRESHOLD)
  )
}) %>% bind_rows()

write.csv(lfc_per_line, file.path(RESULTS_DIR, "tables", "05_lfc_per_line.csv"), row.names = FALSE)

tab_per_line <- lfc_per_line %>% count(Model, Classification) %>%
  tidyr::pivot_wider(names_from = Classification, values_from = n, values_fill = 0)
cat("  Distinctive genes per line (|LFC| >=", LOGFC_THRESHOLD, "versus the others):\n")
print(as.data.frame(tab_per_line))
cat("\n")

# Distinctive genes: those that ONLY one line has beyond the threshold
distinctive <- lfc_per_line %>%
  filter(Classification != "Other") %>%
  group_by(Gene) %>%
  filter(n() == 1) %>%
  ungroup() %>%
  arrange(Model, desc(abs(LFC_vs_others)))

write.csv(distinctive, file.path(RESULTS_DIR, "tables", "05_distinctive_genes_per_line.csv"), row.names = FALSE)
cat("  Distinctive genes of a single line (not shared):", nrow(distinctive), "\n")
for (li in resistant) {
  n_li <- sum(distinctive$Model == li)
  cat("    ", li, ":", n_li, "\n")
}
cat("\n")

cat("4. Cross-referencing distinctive genes with alk_resistance_core and wes_panel_alk...\n")
distinctive_core <- distinctive %>% filter(Gene %in% alk_resistance_core)
distinctive_wes  <- distinctive %>% filter(Gene %in% wes_panel_alk)
cat("  alk_resistance_core:", paste0(distinctive_core$Gene, " [", distinctive_core$Model, "]", collapse = ", "), "\n")
cat("  wes_panel_alk:      ", paste0(distinctive_wes$Gene,  " [", distinctive_wes$Model,  "]", collapse = ", "), "\n\n")
write.csv(distinctive_wes, file.path(RESULTS_DIR, "tables", "05_distinctive_genes_wes_panel.csv"), row.names = FALSE)

# STEP 3: PAIRED SCATTERS BETWEEN ALL LINES ----------------------------
cat("5. Paired scatters between lines (", choose(length(resistant), 2), "pairs )...\n")

pares <- combn(resistant, 2, simplify = FALSE)
for (par in pares) {
  a <- par[1]; b <- par[2]
  df_ab <- tibble::tibble(
    Gene = rownames(mat_res),
    A    = mat_res[, a],
    B    = mat_res[, b]
  ) %>%
    mutate(
      Diff  = A - B,
      label = ifelse(Gene %in% FORCED_GENES | abs(Diff) > LOGFC_THRESHOLD * 1.5, Gene, "")
    )
  r_val <- round(cor(df_ab$A, df_ab$B), 3)

  p_pair <- ggplot(df_ab, aes(A, B)) +
    geom_point(alpha = 0.3, size = 0.7, color = "#555555") +
    geom_abline(slope = 1, intercept = 0, linetype = "dashed", color = "gray50") +
    geom_text_repel(aes(label = label), size = 2.5, max.overlaps = 20,
                    segment.size = 0.2, box.padding = 0.3, color = "#e67e22", seed = 1) +
    labs(
      title = paste0("Expression ", a, " vs ", b, " — ", OUT_PREFIX),
      subtitle = paste("Pearson r =", r_val),
      x = paste("log2CPM —", a), y = paste("log2CPM —", b)
    ) +
    theme_minimal(base_size = 12) +
    theme(plot.title = element_text(face = "bold"),
          panel.background = element_rect(fill = "white"),
          plot.background  = element_rect(fill = "white"))

  fname <- paste0("05_scatter_", a, "_vs_", b, ".png")
  ggsave(file.path(RESULTS_DIR, "figures", fname), p_pair, width = 8, height = 7, dpi = 300)
  cat("  →", fname, "(r =", r_val, ")\n")
}
cat("\n")

# STEP 4: HEATMAP OF MOST VARIABLE GENES BETWEEN LINES + DISTINCTIVE + FORCED ---
cat("6. Heatmap of most variable genes between the 5 lines...\n")

var_res    <- apply(mat_res, 1, var)
top_var    <- names(sort(var_res, decreasing = TRUE))[seq_len(min(TOP_N_VARIANZA, length(var_res)))]
genes_hm   <- union(FORCED_GENES, top_var)
genes_hm   <- genes_hm[genes_hm %in% rownames(mat)]

z_mat <- t(apply(mat[genes_hm, resistant, drop = FALSE], 1, cal_zscore))

ph_var <- pheatmap(z_mat,
         color             = heatmap_expr,
         show_rownames     = (length(genes_hm) <= 60),
         show_colnames     = TRUE,
         fontsize_row      = 7,
         annotation_col    = ann_res,
         annotation_colors = ann_colors_res,
         cluster_rows      = TRUE,
         cluster_cols      = TRUE,
         clustering_method = "ward.D2",
         main = paste0("Top ", length(top_var), " most variable genes between lines + forced — ", OUT_PREFIX),
         silent = TRUE)
grid::grid.newpage()
grid::grid.draw(ph_var$gtable)
save_pheatmap(ph_var, file.path(RESULTS_DIR, "figures", "05_heatmap_variable_between_lines.png"),
              width = 8, height = 10)
cat("  → 05_heatmap_variable_between_lines.png (", length(genes_hm), "genes)\n\n")

# ==============================================================================
# STEP 5 (ALK2-SPECIFIC): IC50 GROUP COMPARISON
# L1/L4/L5 (shifted IC50, real resistance by MTT) vs L2/L3 (tolerated the
# drug but without IC50 shift) -- partition known beforehand,
# not inferred from the data. Looks for what may explain that phenotypic difference.
# ==============================================================================
cat("7. IC50 group comparison (L1/L4/L5 vs L2/L3)...\n")

grp_A <- GRUPOS_IC50$IC50_desplazado
grp_B <- GRUPOS_IC50$IC50_sin_desplazar
cat("  Shifted IC50 (", paste(grp_A, collapse = ", "), ") vs ",
    "Unshifted IC50 (", paste(grp_B, collapse = ", "), ")\n", sep = "")

expr_A <- if (length(grp_A) > 1) rowMeans(mat_res[, grp_A]) else mat_res[, grp_A]
expr_B <- if (length(grp_B) > 1) rowMeans(mat_res[, grp_B]) else mat_res[, grp_B]
lfc_grupo <- expr_A - expr_B

grupo_table <- tibble::tibble(
  Gene              = rownames(mat_res),
  Mean_Expr_Shifted    = expr_A,
  Mean_Expr_SinDesplazar  = expr_B,
  LFC_Shifted_vs_Unshifted = lfc_grupo,
  Classification    = classify_lfc(lfc_grupo, LOGFC_THRESHOLD)
)
write.csv(grupo_table, file.path(RESULTS_DIR, "tables", "05_lfc_ic50_group.csv"), row.names = FALSE)

tab_grupo <- table(grupo_table$Classification)
cat("  Distribution:\n")
for (cls in names(tab_grupo)) cat("    ", cls, ":", tab_grupo[cls], "\n")
cat("\n")

# Cross-reference with curated panels
grupo_up   <- grupo_table %>% filter(Classification == "Upregulated")   %>% arrange(desc(LFC_Shifted_vs_Unshifted))
grupo_down <- grupo_table %>% filter(Classification == "Downregulated") %>% arrange(LFC_Shifted_vs_Unshifted)

grupo_core_up   <- intersect(grupo_up$Gene,   alk_resistance_core)
grupo_core_down <- intersect(grupo_down$Gene, alk_resistance_core)
grupo_wes_up    <- intersect(grupo_up$Gene,   wes_panel_alk)
grupo_wes_down  <- intersect(grupo_down$Gene, wes_panel_alk)

cat("  alk_resistance_core — higher in Shifted:", paste(grupo_core_up, collapse = ", "), "\n")
cat("  alk_resistance_core — higher in Unshifted:", paste(grupo_core_down, collapse = ", "), "\n")
cat("  wes_panel_alk — higher in Shifted:", paste(grupo_wes_up, collapse = ", "), "\n")
cat("  wes_panel_alk — higher in Unshifted:", paste(grupo_wes_down, collapse = ", "), "\n\n")

# Heatmap: top genes separating the 2 groups + forced
top_grupo_up   <- head(grupo_up$Gene, TOP_N_GRUPO / 2)
top_grupo_down <- head(grupo_down$Gene, TOP_N_GRUPO / 2)
genes_grupo    <- union(FORCED_GENES, c(top_grupo_up, top_grupo_down))
genes_grupo    <- genes_grupo[genes_grupo %in% rownames(mat)]

if (length(genes_grupo) >= 2) {
  z_grupo <- t(apply(mat[genes_grupo, resistant, drop = FALSE], 1, cal_zscore))

  ph_grupo <- pheatmap(z_grupo,
           color             = heatmap_expr,
           show_rownames     = TRUE,
           show_colnames     = TRUE,
           fontsize_row      = 7,
           annotation_col    = ann_res,
           annotation_colors = ann_colors_res,
           cluster_rows      = TRUE,
           cluster_cols      = FALSE,
           clustering_method = "ward.D2",
           main = paste0("Shifted IC50 (L1/L4/L5) vs unshifted (L2/L3) — ", OUT_PREFIX,
                         " (", length(top_grupo_up), " up / ", length(top_grupo_down), " down + forced)"),
           silent = TRUE)
  grid::grid.newpage()
  grid::grid.draw(ph_grupo$gtable)
  save_pheatmap(ph_grupo, file.path(RESULTS_DIR, "figures", "05_heatmap_ic50_group.png"),
                width = 8, height = 10)
  cat("  → 05_heatmap_ic50_group.png (", length(genes_grupo), "genes,",
      length(top_grupo_up), "up /", length(top_grupo_down), "down)\n\n")
} else {
  cat("  Fewer than 2 genes distinguish the groups — heatmap skipped\n\n")
}

# REPORT ----------------------------------------------------------------------
cat("8. Generating report...\n")

report_text <- paste0(
  "# Comparison between resistant lines — ", OUT_PREFIX, "\n\n",
  "**Question 1:** how do L1-L5 differ from each other, beyond what they all share relative to the parental/treated?\n",
  "**Question 2 (ALK2-specific):** what distinguishes L1/L4/L5 (shifted IC50, true resistance by MTT) from L2/L3 ",
  "(tolerated the drug but without IC50 shift)?\n",
  "**Method:** direct LFC (no technical replicates -> no formal statistical test). Threshold |LFC| >= ", LOGFC_THRESHOLD, "\n\n",
  "## 1. Correlation between lines (Pearson, log2CPM)\n",
  paste(capture.output(print(round(cor_mat, 3))), collapse = "\n"), "\n\n",
  "## 2. Distinctive genes per individual line (outside threshold in a single line only)\n",
  paste(capture.output(print(as.data.frame(tab_per_line), row.names = FALSE)), collapse = "\n"), "\n",
  "- Total distinctive (not shared between lines): ", nrow(distinctive), "\n\n",
  "## 3. Overlap of per-line distinctive genes with curated panels\n",
  "- alk_resistance_core: ", if (nrow(distinctive_core) > 0)
    paste0(distinctive_core$Gene, " [", distinctive_core$Model, "]", collapse = ", ") else "none", "\n",
  "- wes_panel_alk: ", if (nrow(distinctive_wes) > 0)
    paste0(distinctive_wes$Gene, " [", distinctive_wes$Model, "]", collapse = ", ") else "none", "\n\n",
  "## 4. Comparison by IC50 group (L1/L4/L5 vs L2/L3)\n",
  "- Upregulated in Shifted: ", tab_grupo["Upregulated"], " | Downregulated: ", tab_grupo["Downregulated"], "\n",
  "- alk_resistance_core higher in Shifted: ", if (length(grupo_core_up) > 0) paste(grupo_core_up, collapse = ", ") else "none", "\n",
  "- alk_resistance_core higher in Unshifted: ", if (length(grupo_core_down) > 0) paste(grupo_core_down, collapse = ", ") else "none", "\n",
  "- wes_panel_alk higher in Shifted: ", if (length(grupo_wes_up) > 0) paste(grupo_wes_up, collapse = ", ") else "none", "\n",
  "- wes_panel_alk higher in Unshifted: ", if (length(grupo_wes_down) > 0) paste(grupo_wes_down, collapse = ", ") else "none", "\n",
  "- See 05_lfc_ic50_group.csv for the full table\n\n",
  "## Forced genes\n",
  "- ", paste(FORCED_GENES, collapse = ", "), " — always included in both heatmaps and labelled in the scatters\n\n",
  "## Tables\n",
  "- 05_correlation_between_lines.csv\n",
  "- 05_lfc_per_line.csv (LFC of each line vs mean of the other 4)\n",
  "- 05_distinctive_genes_per_line.csv (only genes exclusive to 1 line)\n",
  "- 05_distinctive_genes_wes_panel.csv\n",
  "- 05_lfc_ic50_group.csv (L1/L4/L5 vs L2/L3, full table)\n\n",
  "## Figures\n",
  "- 05_distances_between_lines.png (with IC50_Group annotation)\n",
  paste(paste0("- 05_scatter_", sapply(pares, `[`, 1), "_vs_", sapply(pares, `[`, 2), ".png\n"), collapse = ""),
  "- 05_heatmap_variable_between_lines.png (top ", length(top_var), " by variance + ",
  paste(FORCED_GENES, collapse = "/"), " forced)\n",
  "- 05_heatmap_ic50_group.png (L1/L4/L5 vs L2/L3, top ", length(top_grupo_up), " up + top ",
  length(top_grupo_down), " down + forced)\n"
)
writeLines(report_text, file.path(RESULTS_DIR, "report", "05_between_lines_report.md"))
cat("Report: report/05_between_lines_report.md\n\n")

cat("================================================================\n")
cat("  BETWEEN RESISTANT LINES completed —", OUT_PREFIX, "\n")
cat("================================================================\n\n")
