# =============================================================================
# ALK_10_fusions_figure.R
# Purpose: RNA fusion figure (STAR-Fusion) of the 3 ALK models.
#   It does not reanalyse the fusions, it starts from the tables of
#   ALK_08.1_*_fusions.R.
#   Panel A -- combined EML4-ALK dotplot (3 style variants:
#              _facetado / _patchwork / _facetado_valores)
#   Panel B -- expression of ALK/EML4, the driver fusion genes of
#              Panel A. Horizontal striplot, direct partner of A.
#   Panel C -- striking fusions, 1 per facet, selected after reviewing the
#              full 08_fusions_all_samples.csv (not only top_striking):
#              absent in Parental, consistently gained in resistant
#              populations, not the event with the most FFPM.
#              ALK1=MBNL2 fusion, ALK2=ARHGAP5--AKAP6,
#              ALK3-Alectinib=LUC7L3--CACNA1G, ALK3-Lorlatinib=DTX2--ZP3.
#              Vertical combined heatmap (rows=samples per facet,
#              columns=fusions), not a striplot, to distinguish it from Panel A.
#   Panel D -- expression of the genes of the 4 fusions of Panel C.
#              Vertical striplot, same row order as Panel C so that
#              both can be read aligned side by side.
#   Fixed colour in B and D: gene to the LEFT of the fusion name = #FFC000,
#   gene to the RIGHT = #D86ECC (same criterion in both figures).
# Inputs:
#   results/ALK/{ALK1,ALK2,ALK3}/tables/08_fusions_driver_trajectory.csv
#   results/ALK/{ALK1,ALK2,ALK3}/tables/08_fusions_all_samples.csv
#   results/ALK/{ALK1,ALK2,ALK3}/tables/01_mat_tmm.csv
# Outputs: results/ALK/combined/{figures,tables}/ALK_10_* (PNG of each panel
#   and variant, aligned A+B PNG, data CSV of each panel)
# Usage: source(here::here("scripts/specific/ALK/ALK_10_fusions_figure.R"))
#   or Rscript from any folder of the repo.
# =============================================================================

