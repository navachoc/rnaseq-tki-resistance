  distinct(Sample, Model, Condition, Drug, Stage, Etiqueta, Faceta) %>%
  mutate(
    Etiqueta = factor(Etiqueta, levels = niveles),
    Faceta   = factor(Faceta, levels = levels(traj$Faceta))
  )

