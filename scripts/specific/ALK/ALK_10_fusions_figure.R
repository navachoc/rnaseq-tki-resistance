leer_todas_fusiones <- function(ruta, modelo) {
  df <- read.csv(ruta, stringsAsFactors = FALSE, check.names = FALSE)
  if (!"Drug" %in% names(df)) df$Drug <- "Lorlatinib"   # ALK1/ALK2 have a single drug
  df$Model <- modelo
  df
}

todas_fusiones <- bind_rows(Map(leer_todas_fusiones, RUTAS_ALL_FUSION, names(RUTAS_ALL_FUSION)))

# The baseline (Untreated) "ALK3" arrives with Drug="No" in the raw CSV -- it
# does not match either of the 2 ALK3 facets (Alectinib/Lorlatinib) and was
# lost entirely from those facets (0 Untreated rows). It is duplicated with
# Drug="Lorlatinib" and Drug="Alectinib", same pattern already used by
# 08_fusions_driver_trajectory.csv of Panel A (same baseline sample
# shared by the 2 drug arms of ALK3).
alk3_untreated <- todas_fusiones %>% filter(Model == "ALK3", Sample == "ALK3")
todas_fusiones <- bind_rows(
  todas_fusiones %>% filter(!(Model == "ALK3" & Sample == "ALK3")),
  alk3_untreated %>% mutate(Drug = "Lorlatinib"),
  alk3_untreated %>% mutate(Drug = "Alectinib")
) %>%
  derivar_stage_etiqueta_faceta()

